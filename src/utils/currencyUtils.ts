/**
 * Detect the local currency for a travel destination.
 * Returns the currency code (e.g. 'PLN', 'JPY') or null if not recognised.
 */
export function detectLocalCurrency(destination: string): string | null {
  if (!destination) return null;
  const lower = destination.toLowerCase();
  for (const [key, cur] of DEST_CURRENCY) {
    if (lower.includes(key.toLowerCase())) return cur;
  }
  return null;
}
